CREATE OR REPLACE FUNCTION public.fn_sold_products_by_date(p_order_date date)
 RETURNS TABLE(product_id integer, product_name character varying, total_quantity integer, total_amount numeric)
 LANGUAGE sql
 STABLE
AS $function$
  select
    p.product_id,
    p.name as product_name,
    sum(oi.quantity)::integer as total_quantity,
    round(sum(oi.line_amount)::numeric, 2) as total_amount
  from public.orders as o
  inner join public.order_items as oi
    on oi.order_id = o.order_id
  inner join public.products as p
    on p.product_id = oi.product_id
  where o.order_date = p_order_date
  group by
    p.product_id,
    p.name
  order by
    sum(oi.quantity) desc,
    p.name asc;
$function$;

CREATE OR REPLACE FUNCTION public.fn_top_categories_by_period(p_date_from date, p_date_to date)
 RETURNS TABLE(category_id integer, category_name character varying, total_quantity integer, total_amount numeric)
 LANGUAGE plpgsql
 STABLE
AS $function$
begin
  if p_date_from > p_date_to then
    raise exception 'Date from cannot be later than date to';
  end if;

  return query
  select
    c.category_id,
    c.category_name,
    sum(oi.quantity)::integer as total_quantity,
    round(sum(oi.line_amount)::numeric, 2) as total_amount
  from public.categories as c
  inner join public.products as p
    on p.category_id = c.category_id
  inner join public.order_items as oi
    on oi.product_id = p.product_id
  inner join public.orders as o
    on o.order_id = oi.order_id
  where o.order_date between p_date_from and p_date_to
  group by
    c.category_id,
    c.category_name
  order by
    sum(oi.quantity) desc,
    sum(oi.line_amount) desc;
end;
$function$;

CREATE OR REPLACE FUNCTION public.pr_create_order(p_customer_id integer, p_order_date date, p_items jsonb, p_payment_method character varying DEFAULT NULL::character varying)
 RETURNS integer
 LANGUAGE plpgsql
AS $function$
declare
  v_order_id integer;
  v_total_amount numeric(12, 2) := 0;
  v_item jsonb;
  v_product_id integer;
  v_quantity integer;
  v_sale_price numeric(12, 2);
  v_discount numeric(5, 2);
  v_stock_quantity integer;
  v_line_amount numeric(12, 2);
begin
  if not exists (
    select 1
    from public.customers
    where customer_id = p_customer_id
  ) then
    raise exception 'Customer with ID % does not exist', p_customer_id;
  end if;

  if p_order_date > current_date then
    raise exception 'Order date cannot be later than current date';
  end if;

  if p_items is null
    or jsonb_typeof(p_items) <> 'array'
    or jsonb_array_length(p_items) = 0 then
    raise exception 'Order must contain at least one item';
  end if;

  if p_payment_method is not null
    and p_payment_method not in ('card', 'iban', 'cash_on_delivery') then
    raise exception 'Payment method must be card, iban, or cash_on_delivery';
  end if;

  insert into public.orders (
    customer_id,
    order_date,
    status,
    total_amount,
    payment_method
  )
  values (
    p_customer_id,
    p_order_date,
    'Created',
    0,
    p_payment_method
  )
  returning order_id into v_order_id;

  for v_item in
    select value
    from jsonb_array_elements(p_items)
  loop
    if not (v_item ? 'product_id') or not (v_item ? 'quantity') then
      raise exception 'Each order item must contain product_id and quantity';
    end if;

    v_product_id := (v_item ->> 'product_id')::integer;
    v_quantity := (v_item ->> 'quantity')::integer;

    if v_quantity <= 0 then
      raise exception 'Order item quantity must be greater than 0';
    end if;

    select
      price,
      discount,
      stock_quantity
    into
      v_sale_price,
      v_discount,
      v_stock_quantity
    from public.products
    where product_id = v_product_id
    for update;

    if not found then
      raise exception 'Product with ID % does not exist', v_product_id;
    end if;

    if v_stock_quantity < v_quantity then
      raise exception 'Not enough stock for product ID %', v_product_id;
    end if;

    v_line_amount := round(
      (v_quantity * v_sale_price * (100 - v_discount) / 100)::numeric,
      2
    );

    insert into public.order_items (
      order_id,
      product_id,
      quantity,
      sale_price,
      discount,
      line_amount
    )
    values (
      v_order_id,
      v_product_id,
      v_quantity,
      v_sale_price,
      v_discount,
      v_line_amount
    );

    update public.products
    set stock_quantity = stock_quantity - v_quantity
    where product_id = v_product_id;

    v_total_amount := v_total_amount + v_line_amount;
  end loop;

  update public.orders
  set total_amount = v_total_amount
  where order_id = v_order_id;

  return v_order_id;
end;
$function$;

CREATE OR REPLACE FUNCTION public.pr_create_shipment(p_order_id integer, p_shipping_service character varying, p_tracking_number character varying, p_shipping_address character varying, p_shipping_status character varying)
 RETURNS integer
 LANGUAGE plpgsql
AS $function$
declare
  v_shipment_id integer;
begin
  if not exists (
    select 1
    from public.orders
    where order_id = p_order_id
  ) then
    raise exception 'Order with ID % does not exist', p_order_id;
  end if;

  if exists (
    select 1
    from public.shipment
    where order_id = p_order_id
  ) then
    raise exception 'Shipment for order ID % already exists', p_order_id;
  end if;

  insert into public.shipment (
    order_id,
    shipping_service,
    tracking_number,
    shipping_address,
    shipping_status
  )
  values (
    p_order_id,
    p_shipping_service,
    p_tracking_number,
    p_shipping_address,
    p_shipping_status
  )
  returning shipment_id into v_shipment_id;

  return v_shipment_id;
end;
$function$;

CREATE OR REPLACE FUNCTION public.pr_register_delivery(p_supplier_id integer, p_delivery_date date, p_invoice_number character varying, p_items jsonb)
 RETURNS integer
 LANGUAGE plpgsql
AS $function$
declare
  v_delivery_id integer;
  v_item jsonb;
  v_product_id integer;
  v_quantity integer;
  v_supply_price numeric(12, 2);
begin
  if not exists (
    select 1
    from public.suppliers
    where supplier_id = p_supplier_id
  ) then
    raise exception 'Supplier with ID % does not exist', p_supplier_id;
  end if;

  if p_delivery_date > current_date then
    raise exception 'Delivery date cannot be later than current date';
  end if;

  if p_items is null
    or jsonb_typeof(p_items) <> 'array'
    or jsonb_array_length(p_items) = 0 then
    raise exception 'Delivery must contain at least one item';
  end if;

  insert into public.deliveries (
    supplier_id,
    delivery_date,
    invoice_number
  )
  values (
    p_supplier_id,
    p_delivery_date,
    p_invoice_number
  )
  returning delivery_id into v_delivery_id;

  for v_item in
    select value
    from jsonb_array_elements(p_items)
  loop
    if not (v_item ? 'product_id')
      or not (v_item ? 'quantity')
      or not (v_item ? 'supply_price') then
      raise exception 'Each supply item must contain product_id, quantity and supply_price';
    end if;

    v_product_id := (v_item ->> 'product_id')::integer;
    v_quantity := (v_item ->> 'quantity')::integer;
    v_supply_price := (v_item ->> 'supply_price')::numeric;

    if v_quantity <= 0 then
      raise exception 'Supply item quantity must be greater than 0';
    end if;

    if v_supply_price <= 0 then
      raise exception 'Supply price must be greater than 0';
    end if;

    perform 1
    from public.products
    where product_id = v_product_id
    for update;

    if not found then
      raise exception 'Product with ID % does not exist', v_product_id;
    end if;

    insert into public.supply_item (
      delivery_id,
      product_id,
      quantity,
      supply_price
    )
    values (
      v_delivery_id,
      v_product_id,
      v_quantity,
      v_supply_price
    );

    update public.products
    set stock_quantity = stock_quantity + v_quantity
    where product_id = v_product_id;
  end loop;

  return v_delivery_id;
end;
$function$;

CREATE OR REPLACE PROCEDURE public.pr_register_payment(IN p_order_id integer, IN p_payment_date date, IN p_payment_method character varying)
 LANGUAGE plpgsql
 SET search_path TO 'public', 'pg_temp'
AS $procedure$
declare
  v_total_amount numeric(12, 2);
begin
  select o.total_amount
  into v_total_amount
  from public.orders as o
  where o.order_id = p_order_id;

  if not found then
    raise exception 'Order with ID % does not exist', p_order_id;
  end if;

  if p_payment_date > current_date then
    raise exception 'Payment date cannot be later than current date';
  end if;

  if exists (
    select 1
    from public.payments as p
    where p.order_id = p_order_id
  ) then
    raise exception 'Payment for order ID % already exists', p_order_id;
  end if;

  insert into public.payments (
    order_id,
    payment_date,
    amount,
    payment_method,
    status
  )
  values (
    p_order_id,
    p_payment_date,
    v_total_amount,
    p_payment_method,
    'Paid'
  );

  update public.orders
  set status = 'Paid'
  where order_id = p_order_id;
end;
$procedure$;

