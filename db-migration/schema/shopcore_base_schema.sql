CREATE OR REPLACE FUNCTION public.fn_customer_orders(p_customer_id integer)
 RETURNS TABLE(order_id integer, order_date date, order_status character varying, total_amount numeric, payment_status character varying, shipping_status character varying)
 LANGUAGE plpgsql
 STABLE
 SET search_path TO 'public', 'pg_temp'
AS $function$
begin
  return query
  select
    o.order_id,
    o.order_date,
    o.status as order_status,
    o.total_amount::numeric(12, 2),
    coalesce(pay.status, 'No payment') as payment_status,
    coalesce(sh.shipping_status, 'No shipment') as shipping_status
  from public.orders as o
  left join public.payments as pay
    on pay.order_id = o.order_id
  left join public.shipment as sh
    on sh.order_id = o.order_id
  where o.customer_id = p_customer_id
  order by o.order_date, o.order_id;
end;
$function$;

